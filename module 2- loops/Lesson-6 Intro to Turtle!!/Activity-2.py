import turtle
turtle.Screen().bgcolor("#F08080")  #hashtag gives color (Hexcode color)
turtle.Screen().setup(500 , 500)
pen = turtle.Turtle()
pen.color("#2E3F2C")
pen.forward(100)
pen.left(120)
pen.forward(100)
pen.left(120)
pen.forward(100)
pen.right(150)

pen.penup()     #penup stops the line from drawn..pen picked up from the paper 
pen.forward(60)
pen.right(90)
pen.pendown()
pen.forward(100)
pen.right(120)
pen.forward(100)
pen.right(120)
pen.forward(100)
pen.right(150)







turtle.done()